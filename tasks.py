from crewai import Task
from agents import professor, visualizer, quizmaster

def create_study_tasks(topic_or_content: str, mode="default"):
    """
    Creates and returns the sequential tasks for the study crew.
    Allows for dynamic task routing based on the selected mode.
    """
    
    is_image = "[IMAGE_PATH]" in topic_or_content
    image_instruction = ""
    if is_image:
        image_instruction = "CRITICAL: The prompt contains an [IMAGE_PATH]. You MUST use the 'Analyze Educational Image' tool on it."

    if mode == "flashcards":
        return [
            Task(
                description=f"Analyze the following material: '{topic_or_content}'. {image_instruction}\n"
                            "Extract exactly the key terms and concepts. You MUST format the output as RAW HTML interactive flashcards using this exact structure:\n"
                            "<div class='flashcard-wrapper'>\n"
                            "  <div class='flip-card'><div class='flip-card-inner'>\n"
                            "    <div class='flip-card-front'><h3>TERM GOES HERE</h3></div>\n"
                            "    <div class='flip-card-back'><p>DEFINITION GOES HERE</p></div>\n"
                            "  </div></div>\n"
                            "  <!-- repeat for all terms -->\n"
                            "</div>\n"
                            "CRITICAL: Do NOT wrap the HTML in ```html blocks. Output the raw HTML code directly so Streamlit can render it natively. Do not add markdown bullet points. Do not say 'Here are the flashcards'. Just output the HTML.",
                expected_output="Pure HTML code containing the interactive flashcards.",
                agent=professor
            )
        ]
        
    elif mode == "quiz":
        return [
            Task(
                description=f"Analyze the following material: '{topic_or_content}'. {image_instruction}\nGenerate a complete, challenging Interactive Quiz (5 multiple choice, 2 short answer) based on the context. Append an Answer Key at the very bottom.",
                expected_output="A complete Markdown practice quiz with answer key.",
                agent=quizmaster
            )
        ]

    elif mode == "syllabus":
        return [
            Task(
                description=f"Analyze the following material: '{topic_or_content}'. {image_instruction}\nGenerate a comprehensive, week-by-week syllabus and structured learning blueprint for this topic.",
                expected_output="A Markdown syllabus outlining a learning curriculum.",
                agent=professor
            )
        ]

    # --- DEFAULT FULL MODE ---
    explain_task = Task(
        description=(
            f"Analyze the following material: '{topic_or_content}'.\n"
            f"{image_instruction}\n"
            "1. Identify the 3 most important core concepts.\n"
            "2. Write a clear, beginner-friendly explanation using analogies.\n"
            "3. Format this as the 'Concept Breakdown' section."
        ),
        expected_output="A detailed, beginner-friendly explanation of the core concepts formatted in Markdown.",
        agent=professor
    )

    visualize_task = Task(
        description=(
            "Identify the key structural components of the educational material.\n"
            "1. Write clean Graphviz DOT syntax representing a BLOCK DIAGRAM (rankdir=LR).\n"
            "   - CRITICAL: Node IDs MUST be strictly alphanumeric with NO spaces.\n"
            "   - CRITICAL: Text labels must be in double-quotes.\n"
            "   - CRITICAL: You MUST wrap your output strictly in a `digraph G { ... }` block.\n"
            "2. Pass this DOT code to the 'Generate Concept Image' tool.\n"
            "3. Return the exact Markdown image link outputted by the tool."
        ),
        expected_output="The exact Markdown image link generated by the tool.",
        agent=visualizer
    )

    compile_task = Task(
        description=(
            "1. Perform a final review of the generated content.\n"
            "2. Generate a 'Practice Quiz' section with 3 MCQs and an Answer Key based on the topic.\n"
            "3. Combine the Professor's Concept Breakdown, the Visualizer's Image Link, and your Practice Quiz into a single, beautifully structured Markdown Study Guide."
        ),
        expected_output="A final, masterfully compiled Markdown study guide.",
        agent=None # The Manager decides who compiles, or the agent can take it
    )

    return [explain_task, visualize_task, compile_task]